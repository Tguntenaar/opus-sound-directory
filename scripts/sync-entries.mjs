import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const dir = path.join(root, "content", "entries");
const files = fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort();

const imports = files
  .map((f) => {
    const id = f.replace(/\.json$/, "").replace(/[^a-zA-Z0-9]/g, "_");
    return `import ${id} from "../content/entries/${f}";`;
  })
  .join("\n");

const ids = files.map((f) => f.replace(/\.json$/, "").replace(/[^a-zA-Z0-9]/g, "_"));

const out = `/* Auto-generated by scripts/sync-entries.mjs — do not edit */\n${imports}\n\nimport type { SoundEntry } from "./entries-types";\n\nexport const ALL_ENTRIES: SoundEntry[] = [${ids.join(", ")}];\n`;

fs.writeFileSync(path.join(root, "lib", "entries.generated.ts"), out);
console.log(`Synced ${files.length} entries → lib/entries.generated.ts`);

const BROWSE_PROMPT_PREFIX = 200;

function slimForBrowse(entry) {
  const prompt =
    entry.prompt.length > BROWSE_PROMPT_PREFIX
      ? entry.prompt.slice(0, BROWSE_PROMPT_PREFIX)
      : entry.prompt;
  return {
    ...entry,
    prompt,
    notes: "",
    cues: undefined,
    seed: 0,
    master: {
      targetLufs: entry.master.targetLufs,
      truePeakDbTp: entry.master.truePeakDbTp,
    },
    metrics: {
      lufs: null,
      truePeak: null,
      durationSec: entry.metrics.durationSec ?? entry.timing.durationSec,
      passedChecks: entry.metrics.passedChecks,
    },
    assets: {
      wav: entry.assets.wav,
      mp3: entry.assets.mp3,
      spectrogram: "",
      code: "",
    },
  };
}

const catalog = files
  .map((f) => slimForBrowse(JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"))))
  .filter((entry) => !entry.hidden);
const browsePath = path.join(root, "public", "catalog", "browse.json");
fs.mkdirSync(path.dirname(browsePath), { recursive: true });
fs.writeFileSync(browsePath, JSON.stringify(catalog));
console.log(`Synced ${catalog.length} browse entries → public/catalog/browse.json`);
