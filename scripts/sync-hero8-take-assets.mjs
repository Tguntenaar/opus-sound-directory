#!/usr/bin/env node
/**
 * Copies Codex hero8 WAVs into public/assets/<entryId>/takes/ and encodes MP3s.
 * Run after changing provenance/codex-generations/hero8/*.wav
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(fileURLToPath(import.meta.url), "..", "..");
const srcRoot = path.join(root, "provenance/codex-generations/hero8");
const measurementsPath = path.join(srcRoot, "measurements.json");

const ENTRY_IDS = [
  "heavy-boom-meme",
  "whoosh-pass-by",
  "ui-cozy-sprite",
  "endless-riser-shepard",
  "dialup-modem-56k",
  "wah-wah-fail",
  "arcade-game-over",
  "trailer-braam-hit",
  "game-coin-pickup",
];

function hasFfmpeg() {
  try {
    execFileSync("ffmpeg", ["-version"], { stdio: "ignore" });
    return true;
  } catch {
    return false;
  }
}

const measurements = JSON.parse(fs.readFileSync(measurementsPath, "utf8"));
const bySlug = new Map();
for (const row of measurements) {
  if (!bySlug.has(row.slug)) bySlug.set(row.slug, []);
  bySlug.get(row.slug).push(row);
}

if (!hasFfmpeg()) {
  console.error("ffmpeg is required to encode take MP3s");
  process.exit(1);
}

let copied = 0;
for (const entryId of ENTRY_IDS) {
  const destDir = path.join(root, "public/assets", entryId, "takes");
  fs.mkdirSync(destDir, { recursive: true });
  for (let take = 1; take <= 3; take += 1) {
    const srcWav = path.join(srcRoot, entryId, `take-${take}.wav`);
    if (!fs.existsSync(srcWav)) {
      console.warn(`missing ${srcWav}`);
      continue;
    }
    const base = `codex-${take}`;
    const destMp3 = path.join(destDir, `${base}.mp3`);
    execFileSync(
      "ffmpeg",
      ["-y", "-i", srcWav, "-codec:a", "libmp3lame", "-qscale:a", "4", destMp3],
      { stdio: "ignore" },
    );
    copied += 1;
  }
}

const manifestRows = [];
for (const entryId of ENTRY_IDS) {
  const rows = (bySlug.get(entryId) ?? []).sort((a, b) => a.take - b.take);
  for (const row of rows) {
    manifestRows.push({
      entryId,
      takeId: `codex-${row.take}`,
      codexTake: row.take,
      lufs: row.lufs,
      truePeakDbTp: row.true_peak_dbtp,
      durationSec: row.duration,
      mp3: `/assets/${entryId}/takes/codex-${row.take}.mp3`,
    });
  }
}

const outTs = `/** Generated by scripts/sync-hero8-take-assets.mjs — do not edit by hand. */
import type { Hero8CodexTakeRow } from "./hero8-takes-types";

export const HERO8_CODEX_TAKE_ROWS: Hero8CodexTakeRow[] = ${JSON.stringify(manifestRows, null, 2)};
`;

fs.writeFileSync(path.join(root, "lib/hero8-takes.generated.ts"), outTs);
console.log(`Synced ${copied} take assets; wrote lib/hero8-takes.generated.ts`);
